//&&,||,!
let mark=15;
//&& checks both conditions are true or not, if both are true then it will return true otherwise false
console.log(mark>15 && mark<25);
//|| checks any one condition is true or not, if any one is true then it will return true otherwise false
console.log(mark>15 || mark<25);
//! checks the opposite of the condition, if the condition is true then it will return false and vice versa
console.log(mark>15);
console.log(!(mark>15));

